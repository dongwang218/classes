class BroadcastTo(TensorOp):
    def __init__(self, shape):
        self.shape = shape

    def compute(self, a):
        return array_api.broadcast_to(a, self.shape)

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        # sum over when axis not equal
        orig_shape = list(node.inputs[0].shape)
        input_shape = orig_shape + [1]*(len(self.shape) - len(orig_shape))
        sum_axis = []
        for index, (a, b) in enumerate(zip(input_shape, self.shape)):
          if a != b:
            sum_axis.append(index)
        return reshape(summation(out_grad, axes=tuple(sum_axis)), tuple(orig_shape))
        ### END YOUR SOLUTION


def broadcast_to(a, shape):
    return BroadcastTo(shape)(a)


class Summation(TensorOp):
    def __init__(self, axes: Optional[tuple] = None):
        self.axes = axes

    def compute(self, a):
        ### BEGIN YOUR SOLUTION
        return array_api.sum(a, axis=self.axes, keepdims=False)
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        out_shape = list(out_grad.shape)
        axes = self.axes
        if axes is None:
          axes = list(range(len(node.inputs[0].shape)))
        for index in axes:
          out_shape.insert(index, 1)
        return broadcast_to(reshape(out_grad, tuple(out_shape)), node.inputs[0].shape)
        ### END YOUR SOLUTION


def summation(a, axes=None):
    return Summation(axes)(a)


